#!/usr/bin/env node
/**
 * Sync Điều khoản tham gia from a public Google Doc into src/content.
 *
 * Usage:
 *   npm run sync:dieu-khoan
 *   npm run sync:dieu-khoan -- --dry-run
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

const DOCUMENT_ID =
  process.env.DIEU_KHOAN_THAM_GIA_DOC_ID ?? "11bNkU9NKZFzDTte2eExnJVcEB3r178Uk9eZ8xgvslMg";
const SOURCE_DOC_URL = `https://docs.google.com/document/d/${DOCUMENT_ID}/edit?usp=sharing`;
const EXPORT_URL = `https://docs.google.com/document/d/${DOCUMENT_ID}/export?format=txt`;
const OUTPUT_PATH = resolve(process.cwd(), "src/content/dieu-khoan-tham-gia.ts");

/** Matches "Điều 1.", "Điều 12:", "Điều 13: Cam kết..." */
const DIEU_HEADING = /^Điều\s+\d+\s*[.:]/u;

function escapeForTemplateLiteral(value) {
  return value.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
}

function normalizeTxtToMarkdown(rawText) {
  const lines = rawText
    .replace(/^\uFEFF/, "")
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter((line) => line.length > 0);

  if (lines.length === 0) {
    throw new Error("Document export returned empty text.");
  }

  const title = lines[0].replace(/\s+/g, " ").trim();
  let subtitle = "";
  let bodyStart = 1;

  if (lines[1] && lines[1].startsWith("(") && !DIEU_HEADING.test(lines[1])) {
    subtitle = lines[1];
    bodyStart = 2;
  }

  const bodyLines = [`# ${title}`];
  if (subtitle) {
    bodyLines.push(subtitle);
  }

  for (let i = bodyStart; i < lines.length; i += 1) {
    const line = lines[i];

    if (DIEU_HEADING.test(line)) {
      bodyLines.push(`## ${line}`);
      continue;
    }

    if (line.startsWith("* ")) {
      bodyLines.push(`- ${line.slice(2)}`);
      continue;
    }

    bodyLines.push(line);
  }

  return {
    title,
    subtitle,
    body: bodyLines.join("\n\n"),
  };
}

function renderContentModule({ title, subtitle, body, lastSyncedAt }) {
  const titleLit = escapeForTemplateLiteral(title);
  const subtitleLit = escapeForTemplateLiteral(subtitle);
  const bodyLit = escapeForTemplateLiteral(body);

  return `/**
 * Auto-generated by \`npm run sync:dieu-khoan\`.
 * Source of truth: Google Doc (see sourceDocUrl).
 * Do not edit body by hand — re-run the sync script instead.
 */

export type DieuKhoanThamGiaContent = {
  title: string;
  subtitle: string;
  body: string;
  sourceDocUrl: string;
  lastSyncedAt: string;
  isDraft: boolean;
};

export const dieuKhoanThamGiaContent: DieuKhoanThamGiaContent = {
  title: \`${titleLit}\`,
  subtitle: \`${subtitleLit}\`,
  body: \`${bodyLit}\`,
  sourceDocUrl: "${SOURCE_DOC_URL}",
  lastSyncedAt: "${lastSyncedAt}",
  isDraft: true,
};
`;
}

async function fetchDocumentText() {
  const response = await fetch(EXPORT_URL, { cache: "no-store" });
  if (!response.ok) {
    throw new Error(
      `Document export failed (${DOCUMENT_ID}): ${response.status}. ` +
        "Ensure the Doc is shared as Anyone with the link → Viewer.",
    );
  }
  return response.text();
}

async function syncDieuKhoan({ dryRun = false } = {}) {
  const rawText = await fetchDocumentText();
  const { title, subtitle, body } = normalizeTxtToMarkdown(rawText);
  const lastSyncedAt = new Date().toISOString();
  const fileContents = renderContentModule({ title, subtitle, body, lastSyncedAt });

  if (!dryRun) {
    mkdirSync(dirname(OUTPUT_PATH), { recursive: true });
    writeFileSync(OUTPUT_PATH, fileContents, "utf8");
  }

  return {
    title,
    subtitle,
    bodyChars: body.length,
    lastSyncedAt,
    outputPath: OUTPUT_PATH,
    sourceDocUrl: SOURCE_DOC_URL,
  };
}

const dryRun = process.argv.includes("--dry-run");

try {
  const result = await syncDieuKhoan({ dryRun });
  const mode = dryRun ? "DRY RUN" : "SYNCED";
  console.log(`[${mode}] Điều khoản tham gia from Google Docs`);
  console.log(`  Source: ${result.sourceDocUrl}`);
  console.log(`  Title: ${result.title}`);
  if (result.subtitle) {
    console.log(`  Subtitle: ${result.subtitle}`);
  }
  console.log(`  Body chars: ${result.bodyChars}`);
  console.log(`  lastSyncedAt: ${result.lastSyncedAt}`);
  console.log(`  Output: ${result.outputPath}`);
} catch (error) {
  const message = error instanceof Error ? error.message : String(error);
  console.error(`sync:dieu-khoan failed: ${message}`);
  process.exit(1);
}
